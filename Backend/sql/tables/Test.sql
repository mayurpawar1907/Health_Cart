CREATE TABLE Test (
  id VARCHAR(30) PRIMARY KEY,
  categoryId VARCHAR(30) NOT NULL,
  name VARCHAR(255) NOT NULL,
  slug VARCHAR(255) NOT NULL UNIQUE,
  shortDescription VARCHAR(500) NOT NULL,
  description TEXT NOT NULL,
  preparation TEXT NOT NULL,
  sampleType VARCHAR(128) NOT NULL,
  reportHours INT NOT NULL DEFAULT 24,
  price DECIMAL(10,2) NOT NULL,
  discountPercent DECIMAL(5,2) NOT NULL DEFAULT 0,
  membershipDiscountPct DECIMAL(5,2) NOT NULL DEFAULT 0,
  membershipEligible TINYINT(1) NOT NULL DEFAULT 0,
  membershipFree TINYINT(1) NOT NULL DEFAULT 0,
  isPopular TINYINT(1) NOT NULL DEFAULT 0,
  isPackage TINYINT(1) NOT NULL DEFAULT 0,
  isActive TINYINT(1) NOT NULL DEFAULT 1,
  faqs JSON NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deletedAt DATETIME(3) NULL,
  INDEX (categoryId),
  INDEX (name),
  INDEX (isPopular, isActive),
  CONSTRAINT fk_test_category FOREIGN KEY (categoryId) REFERENCES TestCategory(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
